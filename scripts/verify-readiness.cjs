require('./load-ts.cjs');
const assert = require('node:assert/strict');
const { AREAS } = require('../src/lib/evaluationFramework.ts');
const { reportReadiness } = require('../src/lib/reportReadiness.ts');
const { computeAreaStats, computeQuestionStat } = require('../src/lib/scoring.ts');
const { emptyManualAnalysis } = require('../src/lib/manualAnalysis.ts');
let count = 0;
const check = (value, label) => { assert.ok(value, label); console.log('[PASS]', label); count++; };
const items = ['teacher','parent','student'].flatMap(a => AREAS.map((area,i) => ({ id:`${a}-${i}`, audience:a, area:area.name, subarea:area.subareas[0], responseType:'likert_5', editedQuestion:`문항 ${a}-${i}` })));
const stats = items.map(i=>computeQuestionStat(i.id,i.audience,['매우 그렇다','그렇다']));
const areaItems = items.map(i=>({...i,questionId:i.id}));
const analysis = emptyManualAnalysis();
analysis.areas.forEach(a=>{ a.findings[0].content='실제 자료로 확인할 가상 의견'; a.findings[0].indicator='평가지표'; });
const result = {itemsSnapshot:items, questionStats:stats, areaStats:computeAreaStats(areaItems,stats), aiAnalysis:analysis};
check(reportReadiness(result).length===0,'전 대상·영역·문항·직접 작성 의견 충족');
const empty = items.map(i=>computeQuestionStat(i.id,i.audience,['','무응답']));
check(computeAreaStats(areaItems,empty).length===0,'응답 부재에 미흡 등급을 부여하지 않음');
check(reportReadiness({...result, questionStats:empty,areaStats:[]}).length>0,'전부 빈 응답 제출 차단');
check(reportReadiness({...result,itemsSnapshot:[...items,{...items[0],id:'missing'}]}).length>0,'같은 영역 안의 누락 문항 제출 차단');
const bad = structuredClone(result);bad.aiAnalysis.areas[0].findings.push({...analysis.areas[0].findings[0],subarea:'이전 세부영역'});
check(reportReadiness(bad).length>0,'추가 의견의 잘못된 세부영역 차단');
const review = structuredClone(result);review.aiAnalysis.consultingNeeds[0].needsReview=true;
check(reportReadiness(review).length>0,'컨설팅 의견의 검토 미완료 차단');
console.log(`완료: ${count}개 통과`);
